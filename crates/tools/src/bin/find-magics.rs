//! Searches for magic numbers and writes `crates/chess/src/magic/magic_numbers.rs`.
//!
//! ```text
//! cargo run --release -p cb2026-tools --bin find-magics [-- <seed>]
//! ```
//!
//! The numbers only need finding once; the engine loads them at startup. Re-run this only if
//! the magic scheme changes. See `cb2026_chess::magic` for how the search works.

use std::process::ExitCode;

use cb2026_chess::magic::find_all_magics;

const OUTPUT: &str = "crates/chess/src/magic/magic_numbers.rs";
const DEFAULT_SEED: u64 = 0x00c0_ffee_d00d_2026;

fn format_array(name: &str, what: &str, numbers: &[u64; 64]) -> String {
    let mut out = format!(
        "/// {what} magic numbers, indexed by square (a1 = 0 ... h8 = 63).\npub const {name}: [u64; 64] = [\n"
    );
    for row in numbers.chunks(4) {
        let cells: Vec<String> = row.iter().map(|n| format!("0x{n:016x}")).collect();
        out.push_str(&format!("    {},\n", cells.join(", ")));
    }
    out.push_str("];\n");
    out
}

fn main() -> ExitCode {
    let seed = match std::env::args().nth(1) {
        Some(arg) => match u64::from_str_radix(arg.trim_start_matches("0x"), 16) {
            Ok(seed) => seed,
            Err(e) => {
                eprintln!("seed must be a hex number: {e}");
                return ExitCode::from(2);
            }
        },
        None => DEFAULT_SEED,
    };
    let start = std::time::Instant::now();
    let (rook, bishop) = find_all_magics(seed);
    let text = format!(
        "//! Magic numbers for cb2026's magic bitboards. Generated by `find-magics` (seed {seed:#x});\n\
         //! don't edit by hand. See `cb2026_chess::magic`.\n\n{}\n{}",
        format_array("ROOK_MAGICS", "Rook", &rook),
        format_array("BISHOP_MAGICS", "Bishop", &bishop),
    );
    if let Err(e) = std::fs::write(OUTPUT, text) {
        eprintln!("{OUTPUT}: {e}");
        return ExitCode::FAILURE;
    }
    println!("Wrote {OUTPUT} in {:.2} s", start.elapsed().as_secs_f64());
    ExitCode::SUCCESS
}
